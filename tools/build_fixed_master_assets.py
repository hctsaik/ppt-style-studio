#!/usr/bin/env python3
"""Extract original package, exact layout placeholder styles and logo; never re-export."""
import base64, hashlib, json, pathlib, zipfile
from lxml import etree as E
ROOT=pathlib.Path(__file__).resolve().parents[1]
SOURCE=ROOT/'fixed-master/Fixed_Red_Template.pptx'
SHA='1d42e27915855f57c1bee5ad185526ee62c51818223e9cfde20609dcf47c1fae'
raw=SOURCE.read_bytes()
assert hashlib.sha256(raw).hexdigest()==SHA, 'Unexpected source: review a new input before changing this contract'
N={'p':'http://schemas.openxmlformats.org/presentationml/2006/main','a':'http://schemas.openxmlformats.org/drawingml/2006/main','r':'http://schemas.openxmlformats.org/officeDocument/2006/relationships'}
with zipfile.ZipFile(SOURCE) as z:
 data={'version':1,'sourceName':'Fixed_Red_Template.pptx','sha256':SHA,'libraryFileId':'libfile_91da4dec0718819188da04d164eaf803','libraryVersion':0,'originalBase64':base64.b64encode(raw).decode(),'parts':{n:hashlib.sha256(z.read(n)).hexdigest() for n in z.namelist() if not n.endswith('/')},'layouts':[]}
 for i in range(1,8):
  root=E.fromstring(z.read(f'ppt/slideLayouts/slideLayout{i}.xml'))
  layout={'number':i,'name':root.find('p:cSld',N).get('name'),'placeholders':{}}
  for sp in root.findall('.//p:sp',N):
   ph=sp.find('.//p:ph',N)
   if ph is None:continue
   idx=ph.get('idx','0');off=sp.find('p:spPr/a:xfrm/a:off',N);ext=sp.find('p:spPr/a:xfrm/a:ext',N)
   body=sp.find('p:txBody',N)
   # Copies retain exact geometry, typography and bullet lists; slide-local UUIDs are not reused.
   for creation in sp.findall('.//{http://schemas.microsoft.com/office/drawing/2014/main}creationId'):
    creation_ext=creation.getparent(); parent=creation_ext.getparent(); parent.remove(creation_ext)
    if len(parent)==0:parent.getparent().remove(parent)
   for para in body.findall('a:p',N):body.remove(para)
   placeholder={'type':ph.get('type','obj'),'index':int(idx),'x':int(off.get('x'))/9525,'y':int(off.get('y'))/9525,'w':int(ext.get('cx'))/9525,'h':int(ext.get('cy'))/9525,'xml':E.tostring(sp,encoding='unicode').replace('</p:txBody>','{{PARAGRAPHS}}</p:txBody>')}
   layout['placeholders'][idx]=placeholder
  data['layouts'].append(layout)
 master=E.fromstring(z.read('ppt/slideMasters/slideMaster1.xml'));pic=master.find('.//p:pic',N);rid=pic.find('.//a:blip',N).get('{'+N['r']+'}embed')
 rel=E.fromstring(z.read('ppt/slideMasters/_rels/slideMaster1.xml.rels'))
 target=next(r.get('Target') for r in rel if r.get('Id')==rid)
 import posixpath
 media=target.lstrip('/') if target.startswith('/') else posixpath.normpath(posixpath.join('ppt/slideMasters',target))
 data['logo']='data:image/png;base64,'+base64.b64encode(z.read(media)).decode()
text='/* Generated by tools/build_fixed_master_assets.py. Original input is immutable. */\n(function(r,d){if(typeof module!=="undefined"&&module.exports)module.exports=d;else r.FixedMasterData=d;})(typeof window!=="undefined"?window:this,'+json.dumps(data,ensure_ascii=False,separators=(',',':'))+');\n'
(ROOT/'fixed-master-data.js').write_text(text, encoding='utf-8', newline='\n')
(ROOT/'fixed-master/source-manifest.json').write_text(json.dumps({k:v for k,v in data.items() if k in ['version','sourceName','sha256','libraryFileId','libraryVersion','parts']},ensure_ascii=False,indent=2)+'\n', encoding='utf-8', newline='\n')
print(f'Fixed master source verified: {SHA}; seven layouts; {len(data["parts"])} original parts')
